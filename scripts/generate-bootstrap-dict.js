const fs = require('fs');
const path = require('path');

const localesDir = path.resolve(__dirname, '../locales');
const enJsonPath = path.join(localesDir, 'en.json');
const clientI18nDir = path.resolve(__dirname, '../client/i18n');
const bootstrapDictPath = path.join(clientI18nDir, 'bootstrap_dict.go');

function generateBootstrapDict() {
    if (!fs.existsSync(enJsonPath)) {
        console.error(`Error: Locales file not found at ${enJsonPath}`);
        process.exit(1);
    }

    const rawData = fs.readFileSync(enJsonPath, 'utf8');
    let enDict;
    try {
        enDict = JSON.parse(rawData);
    } catch (e) {
        console.error(`Error: Invalid JSON in ${enJsonPath}`, e);
        process.exit(1);
    }

    if (!fs.existsSync(clientI18nDir)) {
        fs.mkdirSync(clientI18nDir, { recursive: true });
    }

    let goCode = `// Code generated by scripts/generate-bootstrap-dict.js. DO NOT EDIT.
// Governance: Security Reviewed, Architecture Controlled, Protocol Frozen, Modularization Enforced.
// Author: Server & Cryptography Engineering Authority, Air Roofers Ltd

package i18n

var BootstrapDict = map[string]string{
`;

    for (const [key, value] of Object.entries(enDict)) {
        const escapedKey = key.replace(/"/g, '\\"');
        const escapedValue = value.replace(/"/g, '\\"').replace(/\n/g, '\\n');
        goCode += `\t"${escapedKey}": "${escapedValue}",\n`;
    }

    goCode += `}
`;

    fs.writeFileSync(bootstrapDictPath, goCode, 'utf8');
    console.log(`Generated ${bootstrapDictPath} successfully from en.json.`);
}

generateBootstrapDict();
